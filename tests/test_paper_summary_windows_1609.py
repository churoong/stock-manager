"""운용 요약 감사 [필수] 1·2 (docs/paper.md 6장, docs/infra.md 25.1609).

지키는 것
- 주간 "이번 주 체결" 은 주초 행 뒤에 장부에 든 체결 — 금요일 장 체결(월요일 행에 듦)도 꼭 한 주에 한 번 센다
- 월간 복기는 그달 행들에 장부로 든 매매만 — 그달 마지막 장의 매매도 꼭 한 번, 복기를 연 달 첫 며칠은 섞지 않는다
"""

from __future__ import annotations

from batch.services import paper as pp
from tests.test_paper_summary_1447 import _체결, _행, 한도


def _이번주(줄: list[str]) -> str:
    # 계좌마다 두 줄 — 체결은 둘째 줄(25.1727)
    i = next(k for k, x in enumerate(줄) if x.startswith("  가치 평가 "))
    return 줄[i + 1].split("이번 주 체결 ")[1].split(" (")[0]


def test_금요일_장_체결은_다음_주_요약에_한_번() -> None:
    fills = [_체결(1, "buy", "2026-10-16", 10_000)]  # 금요일 장 — 10-19(월) 행에 든다
    행 = {d: _행("A", d, 1_000_000, 1_000_000, 1.0) for d in ("2026-10-09", "2026-10-16", "2026-10-19", "2026-10-23")}
    # 10-18(일) 요약 — 아직 장부에 없다
    줄 = pp.summary_lines({"A": [행["2026-10-09"], 행["2026-10-16"]]}, {"A": fills}, "2026-10-11", None, {}, {}, 한도)
    assert _이번주(줄) == "매수 0·매도 0"
    # 10-25(일) 요약 — 주초 행(10-16) 뒤에 들었다. 예전엔 체결일(10-16) < 주초(10-18) 라 빠졌다
    줄 = pp.summary_lines({"A": [행["2026-10-16"], 행["2026-10-19"], 행["2026-10-23"]]}, {"A": fills}, "2026-10-18", None,
                         {}, {}, 한도)  # fmt: skip
    assert _이번주(줄) == "매수 1·매도 0"


def test_월말_마지막_장_매도는_다음_복기에_한_번_다음_달_첫날은_안_섞는다() -> None:
    fills = [_체결(1, "buy", "2026-09-01", 10_000), _체결(2, "sell", "2026-10-30", 12_000, qty=5),
             _체결(3, "sell", "2026-11-03", 13_000, qty=5)]  # fmt: skip
    행 = {d: _행("A", d, 1_000_000, 1_000_000, 1.0)
         for d in ("2026-09-30", "2026-10-15", "2026-10-30", "2026-11-02", "2026-11-04", "2026-11-30", "2026-12-01")}
    # 10월 복기(11-05 요약) — 10-30 매도는 아직 10-30 행에 없고, 11-03 매도는 11월 몫
    줄 = pp.summary_lines({"A": [행[d] for d in ("2026-09-30", "2026-10-15", "2026-10-30", "2026-11-02", "2026-11-04")]},
                         {"A": fills}, "2026-10-29", "2026-10-01", {1: "가"}, {}, 한도)  # fmt: skip
    assert "[가상모의투자 월간 복기] 2026-10-01 부터 2026-11-01 전까지" in 줄
    assert "  가치: 그달 판 종목 없음" in 줄
    # 11월 복기 — 10-30 매도(11-02 행에 듦)와 11-03 매도 둘 다. 예전엔 10-30 이 체결일로 잘려 영영 빠졌다
    줄 = pp.summary_lines({"A": [행[d] for d in ("2026-10-30", "2026-11-02", "2026-11-04", "2026-11-30", "2026-12-01")]},
                         {"A": fills}, "2026-11-24", "2026-11-01", {1: "가"}, {}, 한도)  # fmt: skip
    이익 = next(x for x in 줄 if x.startswith("  가치 이익 셋"))
    assert 이익.count("가 +") == 2


def test_주초_행이_없으면_week_start_부터_전체_이력이_아니다() -> None:
    """25.1611 — 25.1609 교차검증 [필수] 2: 배치 공백으로 주초 앞 행이 없으면 처음부터 셌다"""
    fills = [_체결(1, "buy", "2026-09-01", 10_000), _체결(2, "sell", "2026-09-10", 12_000),
             _체결(3, "buy", "2026-09-11", 10_000), _체결(4, "buy", "2026-10-15", 10_000)]  # fmt: skip
    daily = {"A": [_행("A", "2026-10-15", 1_000_000, 1_000_000, 1.0), _행("A", "2026-10-16", 1_000_000, 1_000_000, 1.0)]}
    assert _이번주(pp.summary_lines(daily, {"A": fills}, "2026-10-11", None, {}, {}, 한도)) == "매수 1·매도 0"
