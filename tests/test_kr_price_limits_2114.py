"""국내 상·하한가를 거래소 방식으로 (25.2114, 11-03 db-status L 줄).

가격제한폭 = 기준가 × 30% 를 **기준가의 호가 단위 미만 절사**, 상한가 = 기준가 + 폭을 그 가격 호가 단위로 내림, 하한가 =
기준가 − 폭을 올림. 예전 식(기준가 × 0.7 을 하한가의 호가 단위로 올림)은 폭을 절사하지 않아 하한가를 낮게 잡았다 —
운영 DB 1년 하한가 근처 종가 27건 가운데 두 식이 갈린 5건 모두 거래소식이 실제 종가였다. 그날 하한가로 갇힌 시장가
매도를 찬 것으로 적었다(가상모의투자가 실제로는 못 팔았을 매도를 판 것으로).
"""

from __future__ import annotations

import math

import pytest

from batch.services import paper as pp
from tests.test_paper_limit_locked_1553 import _o


@pytest.mark.parametrize(
    ("기준", "상한", "하한"),
    [
        (2_005, 2_605, 1_405),  # 폭 601.5 → 5원 단위 절사 600. 예전 하한 1,404
        (10_000, 13_000, 7_000),
        (12_340, 16_040, 8_640),
        (3_995, 5_190, 2_800),  # 폭 1,195 → 5,190(10원 단위 내림)·2,800
        (4_990, 6_480, 3_495),
        (20_050, 26_050, 14_050),  # 폭 6,015 → 50원 단위 6,000
        (49_950, 64_900, 35_000),
    ],
)
def test_거래소_방식_상하한(기준: float, 상한: float, 하한: float) -> None:
    assert pp.kr_price_limits(기준) == (상한, 하한)


@pytest.mark.parametrize("기준", [1_003, 2_005, 4_985, 9_990, 20_050, 49_950, 199_900, 498_000, 777_000])
def test_새_식은_예전_식보다_보수_쪽(기준: float) -> None:
    """상한가는 예전 이하·하한가는 예전 이상 — 갇혔다고 보는 날이 늘기만 한다(덜 사고 덜 판다). 기준가는 호가 단위 위의
    값(전날 종가)만 — 9,995 처럼 그 구간 호가에 없는 값은 반올림으로 기준이 바뀐다"""
    상한, 하한 = pp.kr_price_limits(기준)
    위, 아래 = 기준 * 1.3, 기준 * 0.7
    예전상 = math.floor(round(위 / pp._tick(위), 6)) * pp._tick(위)
    예전하 = math.ceil(round(아래 / pp._tick(아래), 6)) * pp._tick(아래)
    assert 상한 <= 예전상 and 하한 >= 예전하


def test_하한가_1405원으로_갇힌_시장가_매도는_안_찬다() -> None:
    """기준가 2,005 → 하한가 1,405(등락률 −29.93%, 소수 둘째 자리). 예전 식은 하한가 1,404 로 보고 1,405 시가 매도를 찼다"""
    매도 = _o(side="sell", ref_price=None)
    가격, 까닭 = pp.judge(매도, pp.Bar("d", 1_405, 1_405, 1_000, -29.93))
    assert 가격 is None and 까닭.endswith(pp.LOCKED_SELL)
    assert pp.judge(매도, pp.Bar("d", 1_406, 1_405, 1_000, -29.93)) == (1_406, "시가")  # 한 단위 위는 찬다


def test_되살린_기준가가_조금_어긋나도_같다() -> None:
    """등락률 소수 둘째 자리로 되살린 기준가(2,005.14)·호가 경계(1,999.7 → 2,000)를 호가 단위로 반올림한다"""
    assert pp.kr_price_limits(1_405 / (1 - 0.2993)) == pp.kr_price_limits(2_005)
    assert pp.kr_price_limits(1_999.7) == pp.kr_price_limits(2_000) == (2_600, 1_400)
