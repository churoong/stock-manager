"""희석 사건 공시 — 종목선정 기법 발굴 루프 3회차 C (docs/factors.md 12.2, docs/infra.md 25.738).

기준일 전 1년 안에 유상증자·전환사채·신주인수권부사채 발행 결정 공시가 있었는가. Loughran & Ritter (1995),
Spiess & Affleck-Graves (1999). 방향은 − (희석 뒤 부진). 자기주식 취득(`buyback`, 2회차 D)의 반대편이다.

**국내만, IC 와 참고 행만** (3회차 두 검증의 조건). 창·이진값·수집 구간 규칙은 `buyback` 과 같다 — 새 숫자가 없다.
제목 문자열은 저장소 fixture 에 근거가 없다 `[확인필요: 실제 DART 제목]` — `buyback.KEYWORD` 와 같은 상태다.

계산만 한다. DB 도 시각도 모른다.
"""

from __future__ import annotations

#: 제목(공백 제거)에 이 중 하나가 있으면 사건. "유무상증자결정" 은 "유상증자결정" 을 부분 문자열로 품지 않아 따로 둔다.
#: 순수 무상증자는 새 돈이 들어오지 않아 희석 사건이 아니다 — 어느 열쇠에도 걸리지 않는다
KEYWORDS = ("유상증자결정", "유무상증자결정", "전환사채권발행결정", "신주인수권부사채권발행결정")
#: 정정은 원공시의 반복, 자회사는 다른 회사(25.484 선례), 교환사채는 자기주식을 내주는 것이라 새 주식이 아니다
#: "종속회사" — 거래소 수시공시 "(종속회사의주요경영사항)" 도 다른 회사다 (25.739, 교차검증) `[확인필요: 실제 제목]`
EXCLUDE = ("정정", "자회사", "종속회사", "교환")


def is_dilution(title: str) -> bool:
    붙인 = title.replace(" ", "")
    return any(k in 붙인 for k in KEYWORDS) and not any(w in 붙인 for w in EXCLUDE)
