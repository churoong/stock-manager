def middle_code(raw: str | int | None) -> str | None:
    """앞 두 자리. 숫자가 아니거나 두 자리보다 짧으면 None. SIC 0000 은 분류 없음으로 본다."""
    text = str(raw or "").strip()
    if len(text) < 2 or not text[:2].isdigit() or text.strip("0") == "":
        return None
    return text[:2]


def kr_sector(induty_code: str | None) -> tuple[str | None, str | None]:
    """(업종 이름, 코드 표기). 예: ("전자부품·컴퓨터·통신장비", "KSIC 26")."""
    code = middle_code(induty_code)
    if code is None:
        return None, None
    return KSIC_MIDDLE.get(code, f"KSIC {code}"), f"KSIC {code}"


def us_sector(sic: str | None) -> tuple[str | None, str | None]:
    """(업종 이름, 코드 표기). 예: ("산업기계·컴퓨터", "SIC 35")."""
    code = middle_code(sic)
    if code is None:
        return None, None
    return SIC_MAJOR.get(code, f"SIC {code}"), f"SIC {code}"


#: 금융업으로 보는 중분류 — 발생액처럼 현금흐름이 이익의 질을 뜻하지 않는 지표에서 뺀다 (factors.md 12.2, 25.452).
#: 미국은 SIC 6000~6999 전체(Fama-French 의 관례: 은행·여신·증권·보험·부동산·지주/투자회사),
#: 국내는 KSIC 64 금융(지주회사 포함)·65 보험·연금·66 금융·보험 관련 서비스·68 부동산 — 미국이 부동산(65)·지주/투자
#: (67)를 빼므로 국내도 부동산을 뺀다. 두 나라가 다른 집합을 빼면 IC 가 나라마다 다른 것을 잰다 (25.457, 교차검증)
FINANCIAL_SIC_MAJOR = frozenset(f"{n}" for n in range(60, 70))
FINANCIAL_KSIC_MIDDLE = frozenset({"64", "65", "66", "68"})


def is_financial(sector_code: str | None) -> bool | None:
    """`stocks.sector_code`("SIC 60", "KSIC 64" — `kr_sector`·`us_sector` 가 적는 모양) 가 금융업인가.

    코드가 없거나 읽을 수 없으면 None(모름)."""
    text = str(sector_code or "").strip()
    scheme, _, raw = text.partition(" ")
    code = middle_code(raw)
    if code is None:
        return None
    if scheme == "SIC":
        return code in FINANCIAL_SIC_MAJOR
    if scheme == "KSIC":
        return code in FINANCIAL_KSIC_MIDDLE
    return None
