--
-- `backtest_runs.calc_version` 은 **엔진 판**(`services/backtest.CALC_VERSION`)이다.
-- 리밸런스·비용·곡선을 내는 방식이 바뀌면 올린다.
--
-- 그런데 백테스트 결과를 실제로 가르는 것의 대부분은 **점수 계산식**이다.
-- 어떤 종목을 고르느냐가 곧 수익률이기 때문이다. 그 판(`services/scoring.CALC_VERSION`)은
-- 어디에도 안 남고 있었다.
--
-- 2026-09-21~22 이틀 동안 스코어링 판의 뜻이 세 번 바뀌었다.
--   · 배당수익률·MAX·잔차 변동성 추가 (CALC_VERSION 3 → 4)
--   · 잔차 변동성의 창이 274일/전 구간 → 252일로 통일 (25.99)
--   · 모멘텀 기준점이 날짜 → 계열로 통일 (25.100)
-- 그 사이에 돌린 백테스트 결과들은 **서로 비교할 수 없는데 표에서는 똑같아 보인다.**
--
-- 기존 행은 NULL 이다. **모르는 것을 지어내지 않는다** — 그때 무슨 판이었는지 실제로 모른다.
-- 화면은 NULL 을 "기록 없음" 으로 적는다.

